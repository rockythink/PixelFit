import Foundation

enum AppLanguage: String, CaseIterable, Codable, Identifiable {
    case system
    case zhHans
    case en

    var id: String { rawValue }

    var label: String {
        switch self {
        case .system: "跟随系统 / System"
        case .zhHans: "中文"
        case .en: "English"
        }
    }

    var resolvedCode: String {
        switch self {
        case .zhHans:
            "zh"
        case .en:
            "en"
        case .system:
            Locale.preferredLanguages.first?.hasPrefix("zh") == true ? "zh" : "en"
        }
    }
}

