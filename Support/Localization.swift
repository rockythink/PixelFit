/// Service errors keep their key so the message follows the in-app language when it is shown.
/// `detail` carries raw diagnostic output (helper or transaction stderr) and is never translated.
struct LocalizedServiceError: LocalizedError {
    let key: String
    var arguments: [String] = []
    var detail: String?

    var errorDescription: String? {
        let message = String(format: L10n.t(key), arguments: arguments.map { $0 as CVarArg })
        guard let detail, !detail.isEmpty else { return message }
        return message + "\n" + detail
    }
}
